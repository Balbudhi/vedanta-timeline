#!/usr/bin/env python3
"""The single whole-Gītā article `gita/bhagavad-gita/` (slug "bhagavad-gita", title "Bhagavad-Gītā").

    python3 scripts/gita/build_whole_gita.py [--root DIR] [--include-legacy] [--register]

Writes DIR/gita/bhagavad-gita/{index.html, reader.js, chapters.js}. chapters.js lists the 18
chapters with their verse counts; a chapter is available when DIR/gita/chN/verses.js exists and
was generated by scripts/build_gita_chapter_reader.py (the pre-standard readers, e.g. ch5, only
with --include-legacy). The reader loads one chapter's verses.js (and audio.js) when it is
opened, so the article never carries all eighteen at once. assets/gita.js is used unchanged.

--register adds the reading to DIR/assets/app.js (GITA_READINGS, inserted before the
yogavasistha-dama entry) and DIR/data/articles/manifest.json (status "provisional"); both are
idempotent. Run it in the deploy worktree, never in a shared working tree with others' edits.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path

sys.path.append(str(Path(__file__).resolve().parent))
from gitapipe import common as C  # noqa: E402

SLUG = "bhagavad-gita"
TITLE = "Bhagavad-Gītā"
GENERATED = "scripts/build_gita_chapter_reader.py"
APP_ENTRY = '''  "bhagavad-gita": {
    base: "gita/bhagavad-gita/",
    files: ["chapters.js", "reader.js"],
    title: "Bhagavad-Gītā",
    blurb: "The eighteen adhyāyas, word by word — choose a chapter; each loads when it is opened.",
    // One article for the whole text: the chapter chooser (gita/bhagavad-gita/reader.js) loads
    // gita/chN/verses.js and audio.js on demand and renders them with GitaReader.
    data: () => ({ verses: [], commentary: null, aurobindo: null, parallels: null, audio: null }),
    afterRender: (root) => window.GitaWhole.mount(root, {
      base: "", glossaryBase: "data/glossary/",
      onGlossary: (term, anchor, opts) => openGlossary(term, anchor, opts),
      onThinker: (id) => openThinker(id),
      linkifyGlossary: linkifyGlossaryText, glossaryResolve: gitaGlossaryResolve,
    }),
  },
'''
ANCHOR = '  "yogavasistha-dama": {'


def chapters(root: Path, include_legacy: bool) -> list[dict]:
    out = []
    for n, count in C.VERSE_COUNTS.items():
        d = root / f"gita/ch{n}"
        v = d / "verses.js"
        head = v.read_text(encoding="utf-8")[:1200] if v.is_file() else ""
        generated = GENERATED in head
        avail = v.is_file() and (generated or include_legacy)
        files = ["verses.js"] + (["audio.js"] if (d / "audio.js").is_file() else [])
        out.append({"n": n, "verses": count, "available": avail, "files": files if avail else [],
                    "standard": "pipeline" if generated else ("legacy" if v.is_file() else None),
                    "v": C.sha256_file(v)[:10] if avail else None})
    return out


def write(root: Path, include_legacy: bool) -> list[dict]:
    out = root / f"gita/{SLUG}"
    out.mkdir(parents=True, exist_ok=True)
    chs = chapters(root, include_legacy)
    (out / "chapters.js").write_text(
        "/* GENERATED by scripts/gita/build_whole_gita.py — the chapters of the whole-Gītā article. */\n"
        f"window.GITA_WHOLE_CHAPTERS = {json.dumps(chs, ensure_ascii=False, indent=1)};\n", encoding="utf-8")
    for f in ("reader.js", "index.html"):
        shutil.copyfile(C.GITA_SCRIPTS / "article" / f, out / f)
    return chs


def register(root: Path, chs: list[dict]) -> None:
    app = root / "assets/app.js"
    s = app.read_text(encoding="utf-8")
    key = f'  "{SLUG}": {{'
    if key in s:
        s = re.sub(rf'  "{SLUG}": \{{.*?\n  \}},\n', lambda _: APP_ENTRY, s, count=1, flags=re.S)
    else:
        if ANCHOR not in s:
            raise SystemExit("app.js GITA_READINGS anchor not found")
        s = s.replace(ANCHOR, APP_ENTRY + ANCHOR, 1)
    app.write_text(s, encoding="utf-8")
    man_p = root / "data/articles/manifest.json"
    man = json.loads(man_p.read_text(encoding="utf-8"))
    arts = man["articles"] if isinstance(man, dict) and "articles" in man else man
    n_av = sum(1 for c in chs if c["available"])
    entry = {"slug": SLUG, "title": TITLE,
             "subtitle": "The whole Bhagavad-Gītā in one reading: choose an adhyāya and read the BORI root text word by word, "
                         "every Sanskrit word tappable for its grammar and meaning, with a literal rendering. "
                         f"{n_av} of 18 chapters published so far.",
             "kind": "reading", "interactive": SLUG, "date": "2026-11-08", "status": "provisional"}
    idx = next((i for i, a in enumerate(arts) if a.get("slug") == SLUG), None)
    if idx is None:
        pos = next((i for i, a in enumerate(arts) if str(a.get("slug", "")).startswith("gita-")), len(arts))
        arts.insert(pos, entry)
    else:
        entry["status"] = arts[idx].get("status", "provisional")
        arts[idx] = entry
    man_p.write_text(json.dumps(man, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", type=Path, default=C.ROOT)
    ap.add_argument("--include-legacy", action="store_true")
    ap.add_argument("--register", action="store_true")
    a = ap.parse_args(argv)
    chs = write(a.root, a.include_legacy)
    if a.register:
        register(a.root, chs)
    print(json.dumps({"root": str(a.root), "available": [c["n"] for c in chs if c["available"]], "registered": a.register}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
